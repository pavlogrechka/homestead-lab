#!/usr/bin/env python3
"""Орієнтовна модель окупності домашньої СЕС із зеленим тарифом.

Усі вхідні дані - припущення, див. docs/. Змінюйте константи нижче.
Запуск: python3 model.py
"""

# --- Припущення ---
KWP = 8.0                  # пікова потужність панелей, кВт
YIELD_KWH_PER_KWP = 1000   # річна віддача, кВт·год/кВт (діапазон 950-1050 для півночі України)
CONSUMPTION_KWH = 7300     # річне споживання будинку, кВт·год (див. docs/01-load-estimate.md)
RETAIL_TARIFF = 4.32       # роздрібний тариф для населення, грн/кВт·год
TAX = 0.23                 # ПДФО 18% + військовий збір 5%, утримує постачальник
TARIFFS = [5.88, 6.134]    # зелений тариф, грн/кВт·год (джерела розходяться, див. docs/03)
CAPEX = [330_000, 375_000, 420_000]  # загальна вартість під ключ, грн (оцінка, див. docs/04)

# Сезонна віддача, кВт·год з 1 кВт на місяць (приблизно)
SEASON = {"грудень": (20, 35), "червень": (130, 150)}


def main() -> None:
    gen = KWP * YIELD_KWH_PER_KWP
    print(f"Генерація: {gen:.0f} кВт·год/рік; споживання: {CONSUMPTION_KWH} кВт·год/рік")
    print(f"Рахунок без СЕС за роздрібним тарифом: {CONSUMPTION_KWH * RETAIL_TARIFF:,.0f} грн/рік")
    print()
    print("Сценарій: уся генерація продається за зеленим тарифом, споживання - з мережі.")
    for t in TARIFFS:
        gross = gen * t
        net = gross * (1 - TAX)
        print(f"\nТариф {t} грн/кВт·год: виручка {gross:,.0f} грн/рік, після податку {net:,.0f} грн/рік")
        for c in CAPEX:
            print(f"  капекс {c:,} грн: окупність {c / gross:.1f} р. (без податку), {c / net:.1f} р. (з податком)")
    print("\nСезонна генерація 8 кВт, кВт·год/міс:")
    for month, (lo, hi) in SEASON.items():
        print(f"  {month}: {KWP * lo:.0f}-{KWP * hi:.0f}")
    print("\nУвага: не враховано деградацію панелей, заміну акумулятора, інфляцію, зміну тарифу.")


if __name__ == "__main__":
    main()
